def check_actions_page() -> list[str]:
    """Return the built-in action names that ``actions.md`` does not mention."""
    names = re.findall(
        r'public const string \w+ = "((?:power|session|display|audio|media|app|url|process|notify)\.\w+)";',
        ACTION_CATALOG.read_text(encoding="utf-8"),
    )
    page = (
        (OUT / "actions.md").read_text(encoding="utf-8")
        if (OUT / "actions.md").exists()
        else ""
    )
    return [name for name in names if f"`{name}`" not in page]


def generate_all() -> dict[str, str]:
    """Return the generated pages as ``{path relative to docs/: content}``.

    Raises ``SystemExit`` when the hand-written actions page lacks a built-in action, so that a new
    action cannot be released without documentation (the MkDocs build then fails).
    """
    missing = check_actions_page()
    if missing:
        raise SystemExit(
            "docs/user/reference/actions.md does not mention: " + ", ".join(missing)
        )
    pages = {
        "user/reference/metrics.md": generate_metrics(),
        "user/reference/protocol.md": generate_protocol(),
        "user/reference/api.md": generate_api(),
    }
    return {path: content.rstrip("\n") + "\n" for path, content in pages.items()}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args()
    for relative, content in generate_all().items():
        path = ROOT / "docs" / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
