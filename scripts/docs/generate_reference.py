def message_section(
    name: str, schema_file: str, *, heading: str, with_t: bool = True
) -> str:
    schema = load_schema(schema_file)
    text = f"{heading} {name}\n\n{schema.get('description', '')}\n\n"
    rows = [row for row in field_rows(schema) if with_t or row[0] != "`t`"]
    text += table(["Field", "Type", "Required", "Description"], rows) + "\n"
    fixture = FIXTURE_DIR / f"{name}.json"
    fixtures = (
        [fixture]
        if fixture.exists()
        else sorted(FIXTURE_DIR.glob(f"{name}.*.json"))[:2]
    )
    for path in fixtures:
        text += example(name, path)
    return text


def example(name: str, path: Path) -> str:
    data = json.loads(path.read_text(encoding="utf-8"))
    return f"Example (`protocol/fixtures/{path.name}`):\n\n```json\n{json.dumps(data, indent=2, ensure_ascii=False)}\n```\n\n"


# --------------------------------------------------------------------------- API


def ref_name(schema: dict[str, Any] | None) -> str:
    if not schema:
        return ""
    if "$ref" in schema:
        return f"`{schema['$ref'].split('/')[-1]}`"
    if schema.get("type") == "array":
        return "array of " + (
            ref_name(schema.get("items")) or schema["items"].get("type", "any")
        )
    return schema.get("type", "")


def api_type(schema: dict[str, Any] | bool) -> str:
    if isinstance(schema, bool):
        return "any" if schema else "never"
    if "$ref" in schema:
        return f"`{schema['$ref'].split('/')[-1]}`"
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    if "oneOf" in schema or "anyOf" in schema:
        return " \\| ".join(
            api_type(o) for o in schema.get("oneOf", schema.get("anyOf", []))
        )
    kind = schema.get("type", "any")
    if isinstance(kind, list):
        kind = " \\| ".join(kind)
    if kind == "array":
        return "array of " + api_type(schema.get("items", {}))
    if (
        kind == "object"
        and "additionalProperties" in schema
        and isinstance(schema["additionalProperties"], dict)
    ):
        return "map of " + api_type(schema["additionalProperties"])
    fmt = schema.get("format")
    return f"{kind} ({fmt})" if fmt else kind


def generate_api() -> str:
    spec = json.loads(OPENAPI.read_text(encoding="utf-8"))
    text = HEADER.format(
        source="the OpenAPI snapshot `tests/QoffeeAutomat.Agent.Tests/Api/openapi.v1.snapshot.json`"
    )
    text += "# API reference (management API v1)\n\n"
    text += spec["info"].get("description", "") + "\n\n"
    text += (
        "The agent serves the live document at `/openapi/v1.json` (it needs a session, like the rest of the API). "
        "Base path: `/api/v1`.\n\n"
        "## Conventions\n\n"
        "* **Authentication.** Everything except `/healthz`, `/auth/setup` (only while a setup token exists) and "
        "`/auth/login` needs a session cookie from `POST /auth/login`. Without it the answer is `401`.\n"
        "* **CSRF.** Requests that change state need the header `X-QoffeeAutomat-Csrf: 1` and, if an `Origin` "
        "header is present, the agent's own origin.\n"
        "* **Loopback only.** Requests from other addresses get `403` unless *remote UI* is switched on in the settings.\n"
        "* **Errors** are RFC 9457 problem details (`application/problem+json`) with a machine-readable `code`. A "
        "document that fails validation is answered with `422` and an `errors` array of `{path, code, message}`.\n"
        "* **Revisions.** Reading a document returns its revision as `ETag`; writes accept `If-Match` and answer "
        "`412` on a stale revision. Creating a document whose id exists answers `409`.\n\n"
    )
    by_tag: dict[str, list[tuple[str, str, dict[str, Any]]]] = {}
    for path, item in spec["paths"].items():
        for method, operation in item.items():
            if not isinstance(operation, dict) or "responses" not in operation:
                continue
            tag = (operation.get("tags") or ["Other"])[0]
            by_tag.setdefault(tag, []).append((method.upper(), path, operation))
    text += "## Operations\n\n"
    for tag in sorted(by_tag):
        text += f"### {tag}\n\n"
        rows: list[list[object]] = []
        for method, path, operation in sorted(by_tag[tag], key=lambda x: (x[1], x[0])):
            needs_session = bool(operation.get("security"))
            body = operation.get("requestBody", {}).get("content", {}).get(
                "application/json", {}
            ).get("schema") or next(
                iter(operation.get("requestBody", {}).get("content", {}).values()), {}
            ).get("schema")
            ok: list[str] = []
            for code, response in operation["responses"].items():
                if code.startswith("2"):
                    content = next(iter(response.get("content", {}).values()), {}).get(
                        "schema"
                    )
                    ok.append(f"{code}" + (f" {ref_name(content)}" if content else ""))
            rows.append(
                [
                    f"`{method}`",
                    f"`{path.replace('/api/v1', '') or '/'}`",
                    operation.get("summary", ""),
                    "session" if needs_session else "none",
                    ref_name(body),
                    ", ".join(ok),
                ]
            )
        text += (
            table(
                ["Method", "Path", "Summary", "Auth", "Request body", "Success"], rows
            )
            + "\n"
        )
    text += "## Schemas\n\n"
    for name, schema in sorted(spec.get("components", {}).get("schemas", {}).items()):
        text += f"### `{name}`\n\n"
        if schema.get("description"):
            text += schema["description"] + "\n\n"
        if schema.get("enum"):
            text += "Values: " + ", ".join(f"`{v}`" for v in schema["enum"]) + "\n\n"
            continue
        properties = schema.get("properties")
        if not properties:
            text += f"Type: {api_type(schema)}\n\n"
            continue
        required = set(schema.get("required", []))
        rows = [
            [
                f"`{prop}`",
                api_type(value),
                "yes" if prop in required else "no",
                value.get("description", "") if isinstance(value, dict) else "",
            ]
            for prop, value in properties.items()
        ]
        text += table(["Member", "Type", "Required", "Description"], rows) + "\n"
    return text


