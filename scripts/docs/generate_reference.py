# --------------------------------------------------------------------------- protocol


def load_schema(name: str) -> dict[str, Any]:
    return json.loads((SCHEMA_DIR / name).read_text(encoding="utf-8"))


DEFS = load_schema("defs.schema.json")["$defs"]


def resolve(schema: dict[str, Any]) -> dict[str, Any]:
    """Follow a ``$ref`` into ``defs.schema.json`` and merge the local keywords over it."""
    ref = schema.get("$ref")
    if not ref:
        return schema
    name = ref.split("/")[-1]
    target = DEFS.get(name, {})
    merged = dict(target)
    merged.update({k: v for k, v in schema.items() if k != "$ref"})
    merged.setdefault("_ref", name)
    return merged


def type_text(schema: dict[str, Any]) -> str:
    schema = resolve(schema)
    if "const" in schema:
        return (
            f'`"{schema["const"]}"`'
            if isinstance(schema["const"], str)
            else f"`{schema['const']}`"
        )
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    if "oneOf" in schema:
        return " \\| ".join(type_text(option) for option in schema["oneOf"])
    kind = schema.get("type")
    if isinstance(kind, list):
        return " \\| ".join(kind)
    if kind == "array":
        return "array of " + type_text(schema.get("items", {}))
    if kind == "object" and "_ref" in schema:
        return f"object (`{schema['_ref']}`)"
    constraints: list[str] = []
    if "minimum" in schema:
        constraints.append(f"≥ {schema['minimum']}")
    if "maximum" in schema:
        constraints.append(f"≤ {schema['maximum']}")
    if "maxLength" in schema:
        constraints.append(f"max {schema['maxLength']} chars")
    return (kind or "any") + (f" ({', '.join(constraints)})" if constraints else "")


def field_rows(schema: dict[str, Any], prefix: str = "") -> list[list[object]]:
    schema = resolve(schema)
    required = set(schema.get("required", []))
    rows: list[list[object]] = []
    for name, raw in schema.get("properties", {}).items():
        prop = resolve(raw)
        description = prop.get("description", "")
        if not description and "_ref" in prop and prop.get("type") == "object":
            description = ""
        rows.append(
            [
                f"`{prefix}{name}`",
                type_text(raw),
                "yes" if name in required else "no",
                description,
            ]
        )
        is_object = prop.get("type") == "object" and "properties" in prop
        if is_object:
            rows += field_rows(prop, f"{prefix}{name}.")
        elif prop.get("type") == "array" and resolve(prop.get("items", {})).get(
            "properties"
        ):
            rows += field_rows(prop["items"], f"{prefix}{name}[].")
    return rows


