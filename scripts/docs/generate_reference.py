def cell(text: object) -> str:
    """Escape a value for a Markdown table cell."""
    return re.sub(r"(?<!\\)\|", r"\\|", str(text)).replace("\n", " ").strip()


def table(headers: list[str], rows: list[list[object]]) -> str:
    lines = [
        "| " + " | ".join(headers) + " |",
        "|" + "|".join("---" for _ in headers) + "|",
    ]
    lines += ["| " + " | ".join(cell(c) for c in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- C# parsing


def split_args(text: str) -> list[str]:
    """Split the arguments of a C# call at top-level commas."""
    args: list[str] = []
    depth = 0
    current: list[str] = []
    in_string = False
    index = 0
    while index < len(text):
        char = text[index]
        if in_string:
            current.append(char)
            if char == "\\":
                index += 1
                current.append(text[index])
            elif char == '"':
                in_string = False
        elif char == '"':
            in_string = True
            current.append(char)
        elif char in "([{":
            depth += 1
            current.append(char)
        elif char in ")]}":
            depth -= 1
            current.append(char)
        elif char == "," and depth == 0:
            args.append("".join(current).strip())
            current = []
        else:
            current.append(char)
        index += 1
    if "".join(current).strip():
        args.append("".join(current).strip())
    return args


def call_arguments(source: str, start: int) -> tuple[list[str], int]:
    """Return the arguments of the call whose opening parenthesis is at ``start`` and the end index."""
    depth = 0
    in_string = False
    index = start
    while index < len(source):
        char = source[index]
        if in_string:
            if char == "\\":
                index += 1
            elif char == '"':
                in_string = False
        elif char == '"':
            in_string = True
        elif char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
            if depth == 0:
                return split_args(source[start + 1 : index]), index
        index += 1
    raise ValueError("unbalanced parenthesis")


def literal(value: str, constants: dict[str, str]) -> Any:
    """Turn a C# literal or a known constant into a Python value."""
    value = value.strip().removeprefix("$")
    if value == "null":
        return None
    if value in ("true", "false"):
        return value == "true"
    if value.startswith('"') and value.endswith('"'):
        return value[1:-1]
    if re.fullmatch(r"-?\d+", value):
        return int(value)
    if re.fullmatch(r"-?\d+\.\d+", value):
        return float(value)
    return constants.get(value.split(".")[-1], value)


def constants_of(path: Path) -> dict[str, str]:
    """Map ``const string Name = "value"`` of a C# file to a dictionary."""
    text = path.read_text(encoding="utf-8")
    return dict(re.findall(r'const string (\w+) = "([^"]*)";', text))


def named(
    args: list[str], constants: dict[str, str]
) -> tuple[list[Any], dict[str, Any]]:
    positional: list[Any] = []
    keyword: dict[str, Any] = {}
    for arg in args:
        match = re.match(r"^(\w+):\s*(.*)$", arg, re.S)
        if match and not arg.startswith('"'):
            keyword[match.group(1)] = literal(match.group(2), constants)
        else:
            positional.append(literal(arg, constants))
    return positional, keyword


def windows_metrics() -> list[dict[str, Any]]:
    """Parse ``BuildDescriptors`` of the Windows system metric provider."""
    constants = constants_of(WINDOWS_METRICS / "SystemMetricIds.cs")
    # ids that are built from a letter or an adapter slug
    dynamic = {
        "DiskFree": "disk.<letter>.free",
        "DiskUsedPercent": "disk.<letter>.used_percent",
        "NetworkReceive": "net.<adapter>.rx",
        "NetworkTransmit": "net.<adapter>.tx",
    }
    source = (WINDOWS_METRICS / "WindowsSystemMetricProvider.cs").read_text(
        encoding="utf-8"
    )
    body = source[source.index("BuildDescriptors(Inventory inventory)") :]
    body = body[: body.index("private Inventory ReadInventory")]
    metrics: list[dict[str, Any]] = []
    for match in re.finditer(r"\b(Number|Text|Flag)\(", body):
        helper = match.group(1)
        args, _ = call_arguments(body, match.end() - 1)
        positional, keyword = named(args, constants)
        first = args[0]
        dyn = re.match(r"SystemMetricIds\.(\w+)\(", first)
        metric_id = dynamic[dyn.group(1)] if dyn else str(positional[0])
        # HTML entities: a bare <drive> would be swallowed as an HTML tag by Markdown.
        name = (
            str(positional[1])
            .replace("{drive}", "&lt;drive&gt;")
            .replace("{adapter.Name}", "&lt;adapter&gt;")
        )
        entry: dict[str, Any] = {
            "id": metric_id,
            "name": name,
            "kind": "binary_sensor" if helper == "Flag" else "sensor",
            "enabled_default": True,
            "context": "system",
        }
        if helper == "Number":
            entry.update(
                value_type="number",
                unit=positional[3],
                interval=keyword["interval"],
                precision=keyword.get("precision"),
                device_class=keyword.get("deviceClass"),
                state_class=keyword.get("stateClass", "measurement"),
                category=keyword.get("entityCategory", "diagnostic"),
            )
        elif helper == "Text":
            device_class = positional[3]
            entry.update(
                value_type="timestamp" if device_class == "timestamp" else "string",
                interval=positional[4] if len(positional) > 4 else keyword["interval"],
                device_class=device_class,
                category="diagnostic",
            )
        else:
            entry.update(
                value_type="bool",
                device_class=positional[3] if len(positional) > 3 else None,
                interval=keyword["interval"],
                category=keyword.get("entityCategory"),
            )
        metrics.append(entry)
    # Battery metrics exist only on computers that have a battery.
    for entry in metrics:
        if entry["id"].startswith("battery."):
            entry["note"] = "Only on computers with a battery."
        if entry["id"].startswith(("disk.", "net.<")):
            entry["note"] = (
                "One pair per fixed volume or network adapter; the set follows the PC."
            )
    return metrics


def session_metrics() -> list[dict[str, Any]]:
    """Parse the ``MetricDescriptor`` blocks of ``SessionMetrics.cs``."""
    source = SESSION_METRICS.read_text(encoding="utf-8")
    ids = constants_of(SESSION_METRICS)
    constants = dict(ids.items())
    metrics: list[dict[str, Any]] = []
    for match in re.finditer(r"new MetricDescriptor\(", source):
        args, _ = call_arguments(source, match.end() - 1)
        first = args[0].split(".")[-1]
        positional, keyword = named(args[1:], constants)
        agent_side = source.rfind("AgentSide", 0, match.start()) > source.rfind(
            "SessionHostSide", 0, match.start()
        )
        metrics.append(
            {
                "id": constants[first],
                "name": positional[0],
                "kind": positional[1],
                "value_type": positional[2],
                "unit": keyword.get("Unit"),
                "device_class": keyword.get("DeviceClass"),
                "state_class": keyword.get("StateClass"),
                "category": keyword.get("EntityCategory"),
                "precision": keyword.get("Precision"),
                "enabled_default": keyword.get("EnabledDefault", True),
                "interval": keyword.get("IntervalSeconds", 0),
                "context": keyword.get("Context"),
                "note": "Reported by the agent itself."
                if agent_side
                else "Sampled by the session helper.",
            }
        )
    return metrics


