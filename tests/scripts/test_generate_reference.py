"""Tests for scripts/docs/generate_reference.py (task T604).

The reference pages of the user documentation are built from the C# metric
catalogs, protocol schemas, and the OpenAPI snapshot. These tests keep the generator
working when a source changes shape, so ``mkdocs build --strict`` stays green.
"""

import importlib.util
import sys
from pathlib import Path
from types import ModuleType

import pytest

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts" / "docs" / "generate_reference.py"


@pytest.fixture(scope="module")
def generator() -> ModuleType:
    spec = importlib.util.spec_from_file_location("generate_reference", SCRIPT)
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules["generate_reference"] = module
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def pages(generator: ModuleType) -> dict[str, str]:
    result: dict[str, str] = generator.generate_all()
    return result


def test_generates_the_three_reference_pages(pages: dict[str, str]) -> None:
    assert set(pages) == {
        "user/reference/metrics.md",
        "user/reference/protocol.md",
        "user/reference/api.md",
    }
    for path, content in pages.items():
        assert content.startswith("<!-- Generated by"), path
        assert content.endswith("\n"), path


def test_metrics_page_lists_system_and_session_metrics(pages: dict[str, str]) -> None:
    text = pages["user/reference/metrics.md"]
    for metric_id in (
        "cpu.usage",
        "memory.used_percent",
        "disk.<letter>.free",
        "net.<adapter>.rx",
        "system.uptime",
        "session.ready",
        "window.title",
        "audio.volume",
        "power.keep_awake",
    ):
        assert f"`{metric_id}`" in text, metric_id


def test_metrics_page_has_no_bare_angle_brackets_in_names(
    pages: dict[str, str],
) -> None:
    # A bare <drive> would be swallowed as an HTML tag by Markdown.
    for line in pages["user/reference/metrics.md"].splitlines():
        if line.startswith("| `"):
            name_cell = line.split("|")[2]
            assert "<" not in name_cell, line


def test_protocol_page_documents_every_message(pages: dict[str, str]) -> None:
    text = pages["user/reference/protocol.md"]
    for heading in (
        "### hello",
        "### client_hello",
        "### subscribe",
        "### state",
        "### run",
        "### result",
        "### pair_request",
        "### manifest",
    ):
        assert heading in text, heading
    assert "unsupported_version" in text


def test_api_page_lists_operations_and_schemas(pages: dict[str, str]) -> None:
    text = pages["user/reference/api.md"]
    assert "## Operations" in text
    assert "## Schemas" in text
    assert "`/commands/{id}/run`" in text


def test_actions_page_names_every_builtin_action(generator: ModuleType) -> None:
    assert generator.check_actions_page() == []
